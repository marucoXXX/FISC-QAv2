def get_original_questions(db_path: Path, session_id: int = 7) -> list[dict]:
    conn = sqlite3.connect(str(db_path))
    conn.row_factory = sqlite3.Row
    rows = conn.execute(
        "SELECT question_no, question_text FROM session_questions "
        "WHERE session_id = ? ORDER BY question_no", (session_id,)
    ).fetchall()
    conn.close()
    return [dict(r) for r in rows]


