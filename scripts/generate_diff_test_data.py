# 過去回答テキスト（差分レベルに応じた回答）
ANSWER_TEMPLATES = {
    "identical": "前年度と同様の対応を継続しています。",
    "minor": "前年度と同様の対応を継続しています。軽微な表記修正を行いました。",
    "small": "前年度の対応に加え、一部運用手順を改善しました。",
    "medium": "前年度から運用体制を見直し、新たな管理手法を導入しています。",
    "large": "前年度の対応を大幅に拡充し、追加的な管理策を導入しています。",
    "different": "該当なし（前年度とは異なる質問項目です）",
}


def generate():
    if not DB_PATH.exists():
        print(f"ERROR: {DB_PATH} not found")
        return

    questions = get_original_questions(DB_PATH)
    if not questions:
        print("ERROR: No questions found for session_id=7")
        return

    conn = sqlite3.connect(str(DB_PATH))

    # 既存の過去回答を削除
    deleted = conn.execute("DELETE FROM past_qa WHERE bank_id = ?", (BANK_ID,)).rowcount
    print(f"Deleted {deleted} existing past_qa records for bank_id={BANK_ID}")

    # バリエーション付き過去回答を挿入
    inserted = 0
    for q in questions:
        qno = q["question_no"]
        original_text = q["question_text"]

        variation = VARIATIONS.get(qno)
        if variation is None:
            past_question = original_text  # 完全一致
        else:
            past_question = variation

        # 差分レベルに応じた回答
        if qno <= 8:
            level = "identical"
            label = "完全一致"
        elif qno <= 16:
            level = "minor"
            label = "微小差分"
        elif qno <= 24:
            level = "small"
            label = "小差分"
        elif qno <= 32:
            level = "medium"
            label = "中差分"
        elif qno <= 40:
            level = "large"
            label = "大差分"
        else:
            level = "different"
            label = "別質問"

        answer = ANSWER_TEMPLATES[level]

        conn.execute(
            "INSERT INTO past_qa (bank_id, question_text, answer_text, choices_text, remarks_text, source_file, created_at) "
            "VALUES (?, ?, ?, '', '', '差分テストデータ', datetime('now'))",
            (BANK_ID, past_question, answer),
        )
        inserted += 1

        # 差分プレビュー
        if variation is not None and qno <= 40:
            print(f"  Q{qno:2d} [{label}] 変更あり")
        elif variation is None:
            print(f"  Q{qno:2d} [{label}] 完全一致")
        else:
            print(f"  Q{qno:2d} [{label}] 別質問")

    conn.commit()
    conn.close()

    print(f"\nInserted {inserted} past_qa records")
    print(f"""
=== 差分グラデーション ===
  Q1-Q8:   完全一致（差分なし）     → 「差分なし ✅」と表示されるべき
  Q9-Q16:  微小差分（句読点等）     → ごく一部だけハイライト
  Q17-Q24: 小差分（語句の言い換え） → 数語がハイライト
  Q25-Q32: 中差分（表現変更）       → 多くの箇所がハイライト
  Q33-Q40: 大差分（条件追加）       → 後半が大きく異なる
  Q41-Q48: 別質問（完全不一致）     → マッチしない可能性あり
""")


if __name__ == "__main__":
    generate()
